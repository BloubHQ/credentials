#!/usr/bin/env bash
#
# Builds the packages of the `client` crate for one platform.
#
#   build/client.sh wasm    OUT VERSION   # OUT/client-wasm-VERSION.tgz: wasm-bindgen package (web)
#   build/client.sh android OUT VERSION   # OUT/client-android-VERSION.zip: jniLibs + Kotlin
#   build/client.sh ios     OUT VERSION   # OUT/client-ios-VERSION.xcframework.zip: + Swift
#
# VERSION is the tag of a release, or anything for a test build; OUT receives the package.
#
# Needs: wasm - wasm-bindgen (the version of the wasm-bindgen crate in Cargo.lock), clang with
# the wasm32 target (CC_wasm32_unknown_unknown, AR_wasm32_unknown_unknown; ring has C code),
# node to run the smoke test; android - ANDROID_NDK_HOME (Linux or macOS host); ios - Xcode.
# The Swift and Kotlin sources are generated by `uniffibindgen`, built from this workspace.
#
# Paths are remapped as in the release build of the CLI, so the libraries do not carry the
# paths of the build machine.

set -euo pipefail

usage="usage: build/client.sh wasm|android|ios OUT VERSION"
platform=${1:?$usage}
out=${2:?$usage}
version=${3:?$usage}

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
target_dir=${CARGO_TARGET_DIR:-$root/target}
mkdir -p "$out"
out=$(cd "$out" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

export RUSTFLAGS="--remap-path-prefix=$root=/src --remap-path-prefix=$HOME/.cargo=/cargo --remap-path-prefix=$HOME/.rustup=/rustup"

build() {
  rustup target add "$1" >&2
  cargo build --release --locked -p client --target "$1" >&2
}

# Generates the bindings of LANGUAGE from LIBRARY into DIR.
bindings() {
  cargo run --locked -p client --features bindgen --bin uniffibindgen -- \
    generate --no-format --library "$2" --language "$1" --out-dir "$3" >&2
}

case "$platform" in
  wasm)
    build wasm32-unknown-unknown
    wasm="$target_dir/wasm32-unknown-unknown/release/client.wasm"
    wasm-bindgen --target web --remove-name-section --out-dir "$work/client" "$wasm"
    ls -l "$work/client" >&2
    node "$root/crates/client/web/smoke.mjs" "$work/client" >&2
    cp crates/client/README.md LICENSE "$work/client/"
    tar -C "$work" -czf "$out/client-wasm-$version.tgz" client
    ;;

  android)
    ndk=${ANDROID_NDK_HOME:?set ANDROID_NDK_HOME to an Android NDK}
    host=$(uname -s | tr '[:upper:]' '[:lower:]')-x86_64
    bin="$ndk/toolchains/llvm/prebuilt/$host/bin"
    mkdir -p "$work/client/jniLibs" "$work/client/kotlin"
    for pair in aarch64-linux-android:arm64-v8a x86_64-linux-android:x86_64; do
      triple=${pair%%:*}
      abi=${pair##*:}
      upper=$(echo "$triple" | tr '[:lower:]-' '[:upper:]_')
      lower=${triple//-/_}
      export "CARGO_TARGET_${upper}_LINKER=$bin/${triple}24-clang"
      export "CC_${lower}=$bin/${triple}24-clang"
      export "AR_${lower}=$bin/llvm-ar"
      build "$triple"
      mkdir -p "$work/client/jniLibs/$abi"
      cp "$target_dir/$triple/release/libclient.so" "$work/client/jniLibs/$abi/"
    done
    # The bindings come from the library before it is stripped: UniFFI reads its metadata.
    bindings kotlin "$work/client/jniLibs/arm64-v8a/libclient.so" "$work/client/kotlin"
    "$bin/llvm-strip" --strip-unneeded "$work"/client/jniLibs/*/libclient.so
    cp crates/client/README.md LICENSE "$work/client/"
    (cd "$work" && zip -qr "$out/client-android-$version.zip" client)
    ;;

  ios)
    for triple in aarch64-apple-ios aarch64-apple-ios-sim; do
      build "$triple"
    done
    bindings swift "$target_dir/aarch64-apple-ios/release/libclient.dylib" "$work/swift"
    mkdir -p "$work/headers" "$work/client/swift"
    cp "$work/swift/clientFFI.h" "$work/headers/"
    cp "$work/swift/clientFFI.modulemap" "$work/headers/module.modulemap"
    cp "$work/swift/client.swift" "$work/client/swift/"
    # The Swift source compiles against the module of the header.
    xcrun --sdk iphonesimulator swiftc -typecheck -module-name client \
      -target arm64-apple-ios15.0-simulator -I "$work/headers" "$work/client/swift/client.swift"
    xcodebuild -create-xcframework \
      -library "$target_dir/aarch64-apple-ios/release/libclient.a" -headers "$work/headers" \
      -library "$target_dir/aarch64-apple-ios-sim/release/libclient.a" -headers "$work/headers" \
      -output "$work/client/client.xcframework" >&2
    cp crates/client/README.md LICENSE "$work/client/"
    (cd "$work" && ditto -c -k --sequesterRsrc --keepParent client "$out/client-ios-$version.xcframework.zip")
    ;;

  *)
    echo "unknown platform $platform: wasm, android or ios" >&2
    exit 2
    ;;
esac

ls -l "$out" >&2
